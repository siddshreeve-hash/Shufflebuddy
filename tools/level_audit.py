# Loudness-matches every sound and kick preset, and works out the default pad levels.
#   build/Audit_artefacts/Release/Audit /tmp/aud && python3 tools/level_audit.py /tmp/aud
# Loudness = K-weighted (ITU BS.1770), loudest 200 ms window, rendered at pad level 0.5.
# Every non-kick sound is trimmed to REF, every kick (Kick Lab presets + "Kicks") to the default kick,
# so swapping sounds or loading a kit never jumps the level. The mix then lives in the pad levels.
import json, sys, math, os
sys.path.insert(0, os.path.dirname(__file__))
D = sys.argv[1]
os.system(f'python3 "{os.path.dirname(__file__)}/loudness.py" "{D}" > /dev/null')
A = json.load(open(D + '/audit.json'))
REF = -22.0                                   # every non-kick sound at pad level 0.5
KREF = next(r['L'] for r in A if r['file'] == 'kick_default')
# mix: loudness of each pad relative to the kick (the snare/clap/hat balance you signed off, perc/shaker/toms pulled into line)
MIX = {'Kick': 0, 'Snare': -15.5, 'Clap': -16.5, 'Rim': -16, 'Hat': -16, 'OpenHat': -16, 'Perc': -15, 'Shaker': -20, 'Toms': -12, 'Crash': -14}
def clamp(x, lo, hi): return max(lo, min(hi, x))
# the audit renders sounds with the trims already in SoundTrims.h, so correct those (kicks are rendered untrimmed)
import re
old = {}
hdr = os.path.join(os.path.dirname(__file__), '..', 'Source', 'SoundTrims.h')
txt = open(hdr).read()
if 'soundTrim (const char* name)' in txt:
    body = txt[txt.index('soundTrim (const char* name)'):txt.index('kickTrim (const char* name)')]
    for n, g in re.findall(r'\{ "([^"]+)", ([0-9.]+)f \}', body): old[n] = 20 * math.log10(float(g))
snd, kick = {}, {}
for r in A:
    if r['file'] == 'kick_default': continue
    if r['cat'] == 'Kick':  kick[r['name']] = clamp(KREF - r['L'], -10, 8)
    elif r['cat'] == 'Kicks': snd[r['name']] = clamp(old.get(r['name'], 0) + KREF - r['L'], -10, 8)
    else:
        o = old.get(r['name'], 0.0)
        t = clamp(o + REF - r['L'], -14, 12)
        t = min(t, o - 4.0 - r['peak'])        # never push a hit's peak past -4 dBFS at half level
        snd[r['name']] = t
kickAbs = KREF + 20 * math.log10(0.85 / 0.5)
lv = {p: round(0.85 if p == 'Kick' else 0.5 * 10 ** ((kickAbs + m - REF) / 20), 3) for p, m in MIX.items()}
def table(d):
    return '\n'.join(f'            {{ "{k}", {10 ** (v / 20):.4f}f }},   // {v:+.1f} dB' for k, v in sorted(d.items()))
h = f'''#pragma once
// GENERATED by tools/level_audit.py - loudness match for every sound and kick preset. Do not edit by hand.
#include <cstring>
namespace sounds
{{
    struct Trim {{ const char* name; float gain; }};
    inline float lookupTrim (const Trim* t, int n, const char* name) {{ for (int i = 0; i < n; ++i) if (std::strcmp (t[i].name, name) == 0) return t[i].gain; return 1.0f; }}
    inline float soundTrim (const char* name)
    {{
        static const Trim t[] = {{
{table(snd)}
        }};
        return lookupTrim (t, (int) (sizeof (t) / sizeof (t[0])), name);
    }}
    inline float kickTrim (const char* name)
    {{
        static const Trim t[] = {{
{table(kick)}
        }};
        return lookupTrim (t, (int) (sizeof (t) / sizeof (t[0])), name);
    }}
    // default pad levels that give the MIX balance above with loudness-matched sounds
    inline float defaultLevel (int pad) {{ static const float l[10] = {{ {', '.join(f'{lv[p]}f' for p in MIX)} }}; return l[pad]; }}
}}
'''
open(os.path.join(os.path.dirname(__file__), '..', 'Source', 'SoundTrims.h'), 'w').write(h)
print('kick ref %.1f  ref %.1f' % (KREF, REF)); print('pad levels', lv)
big = sorted(snd.items(), key=lambda kv: -abs(kv[1]))[:12]
print('biggest trims:', ', '.join(f'{k} {v:+.1f}' for k, v in big))
